          <p>The BDS program is focused on the professional knowledge and skill development with an emphasis on ethical values as our priority and our mission. Department of Dental Sciences also share the Undergraduate Medical Research (UMR) program as a regular component of the education program. We have experienced highly qualified faculty members, state of art well equipped departments, library & laboratories.</p>
          
          <p>Department of Dental Sciences has its own hospital which is one of tertiary care teaching hospital of the Peshawar. Hospital is providing outstanding patient care that is our prime responsibility, also help in providing uninterrupted training facilities both to the undergraduate and postgraduate students of Riphah international university and college of physician and surgeons Pakistan (CPSP). The Operation Theater runs regularly providing services to the patients of oral and maxillofacial surgery. Preclinical Skill development is provided at surgical skill labs and phantom lab in PMC &DC. Clinical skills are developed in small groups in the clinical premises under the supervision of the faculty.</p>
          
